"""Turn the vocabulary CSVs into the data file the prototype reads.

The CSVs stay the single source of truth: edit them, run the check, then this.
  python3 validate_vocabulary.py && python3 build_data.py
"""
import csv, json
from pathlib import Path

HERE = Path(__file__).parent
vibes = list(csv.DictReader(open(HERE / "vibe_vocabulary_v0.csv")))
for v in vibes:
    v["alt_labels"] = [a for a in v["alt_labels"].split("|") if a]
    v["clarify_options"] = [o for o in v["clarify_options"].split("|") if o]
ambiguous = [{"term": r["term"], "why": r["why it isn't mapped"]}
             for r in csv.DictReader(open(HERE / "ambiguous_terms_v0.csv"))]

out = HERE / "docs" / "data" / "vocabulary.js"
out.write_text(
    "// Generated by build_data.py from vibe_vocabulary_v0.csv and ambiguous_terms_v0.csv. Don't edit by hand.\n"
    f"window.VOCAB = {json.dumps({'vibes': vibes, 'ambiguous': ambiguous}, indent=1)};\n"
)
# Publish the source files next to the site so the case study can link to them.
import shutil
files = HERE / "docs" / "files"
files.mkdir(exist_ok=True)
for name in ["vibe_vocabulary_v0.csv", "ambiguous_terms_v0.csv", "golden_set_v0.csv", "validate_vocabulary.py", "running_tempo_source.md"]:
    shutil.copy(HERE / name, files / name)

print(f"wrote {out.relative_to(HERE)}: {len(vibes)} vibes, {len(ambiguous)} ambiguous terms")
